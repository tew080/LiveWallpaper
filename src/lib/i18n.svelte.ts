const DICT: Record<"en" | "th", Record<string, string>> = { en, th };

let current = $state<"en" | "th">("en");

/** `pref` is the saved choice: "en", "th" or "auto" (follow the system language). */
export function setLanguage(pref: string) {
  const system = typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("th");
  current = pref === "th" || pref === "en" ? pref : system ? "th" : "en";
}

export function t(key: string, vars?: Record<string, string | number>): string {
  let text = DICT[current][key] ?? DICT.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}
